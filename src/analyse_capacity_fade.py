"""Analyse discharge-capacity fade in the NASA battery cycle summary.

This script uses the cycle summary generated by Stage 1. It reports data-quality
checks and creates a plot of capacity versus discharge-cycle index. It does not
fit a lifetime model or infer end-of-life unless a documented threshold is
provided and justified separately.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


REQUIRED = {"cycle_number", "cycle_type", "capacity_Ah"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input", type=Path,
        default=Path(
            r"C:\Users\Ajmal\battery-digital-twin\data\processed\B0005_cycle_summary.csv"
        ),
        help="Stage 1 cycle-summary CSV",
    )
    parser.add_argument("--out-dir", type=Path, default=Path("results"))
    args = parser.parse_args()

    if not args.input.is_file():
        parser.error(f"Input not found: {args.input}. Run Stage 1 first.")

    df = pd.read_csv(args.input)
    missing = REQUIRED - set(df.columns)
    if missing:
        parser.error(f"Input is missing required columns: {sorted(missing)}")

    dis = df.loc[
        df["cycle_type"].astype(str).str.lower().eq("discharge")
    ].copy()
    dis["cycle_number"] = pd.to_numeric(dis["cycle_number"], errors="coerce")
    dis["capacity_Ah"] = pd.to_numeric(dis["capacity_Ah"], errors="coerce")
    total_discharge_rows = len(dis)
    invalid = dis["capacity_Ah"].isna() | ~np.isfinite(dis["capacity_Ah"]) | (dis["capacity_Ah"] <= 0)
    invalid_count = int(invalid.sum())
    valid = dis.loc[~invalid].sort_values("cycle_number").copy()

    if len(valid) < 2:
        parser.error("Need at least two valid discharge capacities to analyse fade.")

    # Duplicate cycle IDs can distort a trend; report and retain a stable first
    # observation only if duplicates exist, while exposing the count.
    duplicate_count = int(valid["cycle_number"].duplicated().sum())
    valid = valid.drop_duplicates(subset="cycle_number", keep="first")

    first = valid.iloc[0]
    last = valid.iloc[-1]
    first_capacity = float(first["capacity_Ah"])
    last_capacity = float(last["capacity_Ah"])
    change_ah = last_capacity - first_capacity
    change_pct = 100.0 * change_ah / first_capacity if first_capacity else np.nan

    # Plot each valid observed discharge point; no smoothing or synthetic data.
    args.out_dir.mkdir(parents=True, exist_ok=True)
    plot_path = args.out_dir / "B0005_capacity_fade.png"
    csv_path = args.out_dir / "B0005_discharge_capacity.csv"
    report_path = args.out_dir / "B0005_capacity_report.txt"

    valid[["cycle_number", "capacity_Ah", "ambient_temperature_C"]].to_csv(
        csv_path, index=False
    )

    fig, ax = plt.subplots(figsize=(9, 5.2))
    ax.plot(valid["cycle_number"], valid["capacity_Ah"], marker="o",
            markersize=3.0, linewidth=1.2)
    ax.set_title("NASA B0005: observed discharge capacity by recorded cycle")
    ax.set_xlabel("Recorded cycle number")
    ax.set_ylabel("Discharge capacity (Ah)")
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(plot_path, dpi=180)
    plt.close(fig)

    report = [
        "NASA B0005 — discharge capacity data-quality report",
        "=" * 52,
        f"Rows classified as discharge: {total_discharge_rows}",
        f"Valid positive finite capacity records before duplicate check: {total_discharge_rows - invalid_count}",
        f"Invalid/missing/non-positive capacity records: {invalid_count}",
        f"Duplicate cycle numbers among initially valid records: {duplicate_count}",
        f"Unique valid discharge capacity records analysed: {len(valid)}",
        f"First analysed recorded cycle: {int(first['cycle_number'])}",
        f"First analysed discharge capacity: {first_capacity:.6f} Ah",
        f"Last analysed recorded cycle: {int(last['cycle_number'])}",
        f"Last analysed discharge capacity: {last_capacity:.6f} Ah",
        f"Absolute capacity change: {change_ah:.6f} Ah",
        f"Relative change from first to last analysed point: {change_pct:.3f}%",
        "",
        "Interpretation limits:",
        "- This is an observed endpoint comparison, not a fitted degradation rate.",
        "- Recorded cycle numbers include charge, discharge and impedance records.",
        "- Do not interpret the cycle-number gap as a count of discharge events.",
        "- No end-of-life threshold or remaining-useful-life prediction is applied.",
        "- Inspect the plot and source metadata before drawing physical conclusions.",
    ]
    report_path.write_text("\n".join(report) + "\n", encoding="utf-8")

    print("\n".join(report))
    print(f"\nCapacity CSV: {csv_path}")
    print(f"Capacity plot: {plot_path}")
    print(f"Text report: {report_path}")


if __name__ == "__main__":
    main()
